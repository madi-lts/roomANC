#!/usr/bin/env python3
"""Rectangular rigid-wall modal model of the room (workstream 2).

Usage: room_modes.py OUTDIR
Writes to OUTDIR:
  room-modes.png      mode ladder up to 150 Hz vs. the measured tone census
  pressure-59hz.png   |p| maps of the modeled field at 59.0 Hz
  pressure-40hz.png   |p| maps of the modeled field at 39.9 Hz
and prints (stdout) the mode table and the mic-array observability
conditioning, both as markdown for the Modes page.

Room: 4.445 x 3.658 x 2.692 m (matches scripts/room_layout.py and layout.qmd).

Model. Rigid-wall eigenfunctions
  psi_n(x,y,z) = cos(nx pi x/Lx) cos(ny pi y/Ly) cos(nz pi z/Lz),
eigenfrequencies f_n = (c/2) sqrt((nx/Lx)^2 + (ny/Ly)^2 + (nz/Lz)^2).
The field at drive frequency f is the damped modal sum
  p(r; f) = sum_n a_n psi_n(r) / (f_n^2 - f^2 + i f df),
with half-power bandwidth df = 2.2/T60 (uniform modal damping) and equal
modal excitation a_n = 1. The true a_n depend on the unknown (structure-
borne, distributed) source coupling, so absolute and inter-mode levels are
indicative only; the *geometry* of the resonant field -- which modes
dominate near a tone and where their null surfaces sit -- is robust to a_n.
"""
import sys
from itertools import product

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

BG, GRID, INK, SERIES, ACCENT, SOFT = ("#fbf1c7", "#d5c4a1", "#3c3836",
                                       "#076678", "#af3a03", "#ebdbb2")
C = 343.0                      # speed of sound (m/s)
LX, LY, LZ = 4.445, 3.658, 2.692
T60 = 0.4                      # assumed reverberation time (s)
DF = 2.2 / T60                 # modal half-power bandwidth (Hz)
FMAX = 150.0

# measured tone census (measurements.qmd), Hz
MEASURED = {39.9: "39.9 machine", 58.95: "59.0 drone", 61.1: "sideband",
            79.9: "2x39.9", 117.9: "2x59.0", 120.0: "mains"}

# mic positions (x, y, h) from layout.qmd / room_layout.py
MICS = {"M1": (1.55, 3.40, 1.10), "M2": (2.60, 3.40, 0.65),
        "M3": (4.25, 1.45, 1.10), "M4": (0.20, 2.30, 1.75),
        "M5": (2.60, 0.30, 1.20), "M6": (2.95, 3.40, 2.10)}
SUBS = {"S1": (0.35, 0.35, True), "S2": (4.09, 0.35, False),
        "S3": (0.35, 3.31, False), "S4": (4.09, 3.31, True)}


def mode_freq(n):
    nx, ny, nz = n
    return (C / 2.0) * np.hypot(np.hypot(nx / LX, ny / LY), nz / LZ)


def mode_family(n):
    k = sum(1 for v in n if v > 0)
    return {1: "axial", 2: "tangential", 3: "oblique"}[k]


def psi(n, x, y, z):
    nx, ny, nz = n
    return (np.cos(nx * np.pi * x / LX) * np.cos(ny * np.pi * y / LY)
            * np.cos(nz * np.pi * z / LZ))


def modes_up_to(fmax):
    nmax = [int(np.ceil(2 * fmax * L / C)) for L in (LX, LY, LZ)]
    out = [(n, mode_freq(n)) for n in product(*(range(m + 1) for m in nmax))
           if n != (0, 0, 0) and mode_freq(n) <= fmax]
    return sorted(out, key=lambda t: t[1])


def pressure(modes, x, y, z, f):
    """Damped modal sum at drive frequency f, equal modal excitation."""
    p = np.zeros(np.broadcast(x, y, z).shape, dtype=complex)
    for n, fn in modes:
        p += psi(n, x, y, z) / (fn**2 - f**2 + 1j * f * DF)
    return p


MODES = modes_up_to(FMAX)
# include modes a bit past FMAX in the field sums so the 150 Hz edge is honest
MODES_SUM = modes_up_to(1.5 * FMAX)

# ---------------- optimal head position ----------------
# minimize the modeled field at head height, weighting 59 Hz 10:1 in power
# over 39.9 Hz (it dominates perceptually); same caveat as the maps: the
# exact spot inherits the equal-excitation assumption.
Z_HEAD = 0.65
_x = np.linspace(0.05, LX - 0.05, 441)
_y = np.linspace(0.05, LY - 0.05, 361)
_X, _Y = np.meshgrid(_x, _y)
_p59 = np.abs(pressure(MODES_SUM, _X, _Y, Z_HEAD, 59.0))
_p40 = np.abs(pressure(MODES_SUM, _X, _Y, Z_HEAD, 39.9))
_metric = 10 * (_p59 / _p59.max())**2 + (_p40 / _p40.max())**2
_i = np.unravel_index(np.argmin(_metric), _metric.shape)
HEAD_OPT = (float(_X[_i]), float(_Y[_i]))
# proposed 1.5 x 2.0 m bed, rotated 180 deg: head toward midroom, foot at
# the current head wall
BED_NEW = (HEAD_OPT[0] - 0.75, HEAD_OPT[1], 1.5, 2.0)
print(f"<!-- optimal head position at z = {Z_HEAD} m: "
      f"({HEAD_OPT[0]:.2f}, {HEAD_OPT[1]:.2f}); "
      f"59 Hz {20*np.log10(_p59[_i]/_p59.max()):.1f} dB, "
      f"39.9 Hz {20*np.log10(_p40[_i]/_p40.max()):.1f} dB re slice max -->")

# ---------------- mode table (markdown, stdout) ----------------
print(f"<!-- generated by scripts/room_modes.py: {len(MODES)} modes <= "
      f"{FMAX:.0f} Hz, df = {DF:.1f} Hz -->")
print("| Mode | $f$ (Hz) | Family | Measured line within "
      "$\\Delta f/2$ |")
print("|---|---:|---|---|")
for n, fn in MODES:
    near = [f"{fm:.1f} Hz ({lbl})" for fm, lbl in MEASURED.items()
            if abs(fm - fn) <= DF / 2]
    print(f"| ({n[0]},{n[1]},{n[2]}) | {fn:.1f} | {mode_family(n)} | "
          f"{'; '.join(near) if near else '—'} |")

counts = {fam: sum(1 for n, _ in MODES if mode_family(n) == fam)
          for fam in ("axial", "tangential", "oblique")}
print(f"\n<!-- counts: {counts} -->")

# ---------------- observability conditioning (markdown, stdout) --------
print("\n## Observability of the 6-mic array\n")
print("| Tone (Hz) | Modes within $\\pm\\Delta f$ | "
      "$\\sigma_{min}$ | $\\sigma_{max}$ | cond($\\Psi$) |")
print("|---:|---|---:|---:|---:|")
for ft in (39.9, 58.95, 79.9, 117.9, 120.0):
    grp = [(n, fn) for n, fn in MODES if abs(fn - ft) <= DF]
    if not grp:
        print(f"| {ft:.1f} | — | | | |")
        continue
    Psi = np.array([[psi(n, *MICS[m]) for n, _ in grp] for m in MICS])
    sv = np.linalg.svd(Psi, compute_uv=False)
    names = ", ".join(f"({n[0]},{n[1]},{n[2]})" for n, _ in grp)
    print(f"| {ft:.1f} | {names} | {sv[-1]:.2f} | {sv[0]:.2f} | "
          f"{sv[0] / sv[-1]:.1f} |")

# ---------------- figure 1: mode ladder vs. measured tones -------------
fig, ax = plt.subplots(figsize=(12, 5.2))
fig.patch.set_facecolor(BG)
ax.set_facecolor(BG)
FAM_COLOR = {"axial": ACCENT, "tangential": SERIES, "oblique": GRID}
FAM_H = {"axial": 1.0, "tangential": 0.75, "oblique": 0.5}
for n, fn in MODES:
    fam = mode_family(n)
    ax.plot([fn, fn], [0, FAM_H[fam]], color=FAM_COLOR[fam], lw=2.2,
            solid_capstyle="butt")
    if fn < 125 and fam != "oblique":
        ax.text(fn, FAM_H[fam] + 0.03, f"({n[0]},{n[1]},{n[2]})",
                rotation=60, ha="left", va="bottom", fontsize=8.5,
                color=FAM_COLOR[fam])
# modal response magnitude (equal excitation) as a guide
fgrid = np.linspace(20, FMAX, 1200)
resp = np.zeros_like(fgrid)
for n, fn in MODES_SUM:
    resp += 1 / np.abs(fn**2 - fgrid**2 + 1j * fgrid * DF)
resp = resp / resp.max() * 1.0
ax.plot(fgrid, resp, color=INK, lw=1.0, alpha=0.45)
for fm, lbl in MEASURED.items():
    ax.axvline(fm, color=INK, ls=":", lw=1.2)
    ax.text(fm, 1.22, f"{fm:g}", rotation=90, ha="center", va="bottom",
            fontsize=8.5, color=INK)
handles = [plt.Line2D([], [], color=FAM_COLOR[f], lw=3, label=f)
           for f in ("axial", "tangential", "oblique")]
handles.append(plt.Line2D([], [], color=INK, ls=":", lw=1.2,
                          label="measured line"))
handles.append(plt.Line2D([], [], color=INK, lw=1, alpha=0.45,
                          label="modal response (equal excitation, a.u.)"))
ax.legend(handles=handles, loc="upper left", frameon=False, fontsize=9,
          labelcolor=INK)
ax.set_xlim(20, FMAX)
ax.set_ylim(0, 1.45)
ax.set_yticks([])
ax.set_xlabel("frequency (Hz)", color=INK)
ax.tick_params(colors=INK)
for s in ax.spines.values():
    s.set_visible(False)
ax.spines["bottom"].set_visible(True)
ax.spines["bottom"].set_color(INK)
ax.set_title(f"Rigid-wall modes to {FMAX:.0f} Hz "
             f"({counts['axial']} axial, {counts['tangential']} tangential, "
             f"{counts['oblique']} oblique) vs. measured tones",
             color=INK, fontsize=13, fontweight="bold", loc="left")
fig.tight_layout()
fig.savefig(f"{sys.argv[1]}/room-modes.png", dpi=150, facecolor=BG,
            bbox_inches="tight")
plt.close(fig)


# ---------------- figures 2-3: |p| maps at the two tones ----------------
def field_figure(f, fname, z_plan, y_elev):
    fig, (ax, axe) = plt.subplots(1, 2, figsize=(14, 6),
                                  gridspec_kw={"width_ratios": [1.15, 1]})
    fig.patch.set_facecolor(BG)
    x = np.linspace(0, LX, 220)
    for a in (ax, axe):
        a.set_facecolor(BG)

    # plan view at z = z_plan
    y = np.linspace(0, LY, 180)
    Xg, Yg = np.meshgrid(x, y)
    P = np.abs(pressure(MODES_SUM, Xg, Yg, z_plan, f))
    P = P / P.max()
    im = ax.pcolormesh(Xg, Yg, 20 * np.log10(np.maximum(P, 1e-3)),
                       cmap="magma", vmin=-30, vmax=0, shading="auto")
    cs = ax.contour(Xg, Yg, P, levels=[0.1], colors=[SERIES],
                    linewidths=1.4, linestyles="--")
    for m, (mx, my, mh) in MICS.items():
        ax.plot([mx], [my], "o", ms=8, color=SERIES, mec="white", mew=1)
        ax.annotate(m, xy=(mx, my), xytext=(mx + 0.08, my - 0.22),
                    color="white", fontsize=9, fontweight="bold")
    for s, (sx, sy, p1) in SUBS.items():
        ax.plot([sx], [sy], "s", ms=9, color=ACCENT if p1 else "none",
                mec=ACCENT, mew=1.5)
    bed = plt.Rectangle((1.40, 1.66), 1.5, 2.0, fill=False, ec="white",
                        lw=1, ls=":")
    ax.add_patch(bed)
    bx, by, bw, bl = BED_NEW
    ax.add_patch(plt.Rectangle((bx, by), bw, bl, fill=False, ec="#8ec07c",
                               lw=1.8, ls="--"))
    ax.plot([HEAD_OPT[0]], [HEAD_OPT[1]], "*", ms=16, color="#8ec07c",
            mec=INK, mew=0.8)
    ax.annotate("optimal pillow\n"
                f"({HEAD_OPT[0]:.2f}, {HEAD_OPT[1]:.2f})",
                xy=HEAD_OPT, xytext=(HEAD_OPT[0] + 0.28, HEAD_OPT[1] - 0.30),
                color="#8ec07c", fontsize=9, fontweight="bold")
    ax.text(bx + bw / 2, by + bl - 0.14, "proposed bed", ha="center",
            color="#8ec07c", fontsize=9, fontweight="bold")
    ax.set_aspect("equal")
    ax.set_title(f"|p| at {f:g} Hz, z = {z_plan} m (pillow height)",
                 color=INK, fontsize=12, fontweight="bold", loc="left")
    ax.set_xlabel("x (m)", color=INK)
    ax.set_ylabel("y (m)", color=INK)
    ax.tick_params(colors=INK)
    cb = fig.colorbar(im, ax=ax, shrink=0.85)
    cb.set_label("dB re max", color=INK)
    cb.ax.tick_params(colors=INK)

    # elevation at y = y_elev
    z = np.linspace(0, LZ, 150)
    Xg, Zg = np.meshgrid(x, z)
    P = np.abs(pressure(MODES_SUM, Xg, y_elev, Zg, f))
    P = P / P.max()
    im = axe.pcolormesh(Xg, Zg, 20 * np.log10(np.maximum(P, 1e-3)),
                        cmap="magma", vmin=-30, vmax=0, shading="auto")
    axe.contour(Xg, Zg, P, levels=[0.1], colors=[SERIES],
                linewidths=1.4, linestyles="--")
    axe.set_aspect("equal")
    axe.set_title(f"|p| at {f:g} Hz, elevation at y = {y_elev} m",
                  color=INK, fontsize=12, fontweight="bold", loc="left")
    axe.set_xlabel("x (m)", color=INK)
    axe.set_ylabel("z (m)", color=INK)
    axe.tick_params(colors=INK)
    cb = fig.colorbar(im, ax=axe, shrink=0.85)
    cb.set_label("dB re max", color=INK)
    cb.ax.tick_params(colors=INK)

    fig.suptitle("equal modal excitation; dashed contour: −20 dB "
                 "(predicted nulls); geometry robust, levels indicative",
                 color=INK, fontsize=10, y=0.02, va="bottom")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(f"{sys.argv[1]}/{fname}", dpi=150, facecolor=BG,
                bbox_inches="tight")
    plt.close(fig)


field_figure(59.0, "pressure-59hz.png", z_plan=0.65, y_elev=2.66)
field_figure(39.9, "pressure-40hz.png", z_plan=0.65, y_elev=2.66)
